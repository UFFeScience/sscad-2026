#!/usr/bin/env python3
"""Application-specific correctness oracles, applied post hoc to the arrays
captured (capture/oracle_capture_hook.py) while re-executing each successful
specification (run_oracle_exec.py), and to the GROMACS logs it left behind.

Criteria (fixed before any result was inspected):

MatMul -- C must equal A.B for the inputs the workflow itself used:
    ||C - A.B||_F <= eps * ||A||_F * ||B||_F,
    eps = 1e-6 (float64 / integer), 1e-3 if any operand is float32/16.
  M1 (global): a captured triple (A, B, C) satisfies the bound and C is the
     largest matrix the run produced.
  M2 (blocked): when the full matrices never coexist in one process (e.g.
     PyCOMPSs workers only see blocks), the task dataflow is rebuilt from the
     captured calls: every multiply task must satisfy the bound for its own
     operands, each output block is expanded into the products it sums, the
     block grid is recovered from the pairing a_ik . b_kj, and the assembled
     C is checked against the assembled A.B with the same bound.
  PASS if M1 or M2 holds; FAIL otherwise.

K-Means -- the result must be a Lloyd iteration over the full input X:
  K1 the final centroid matrix (k x d, 2 <= k <= 64) is finite, has k distinct
     rows, and lies inside the bounding box of X;
  K2 it equals one Lloyd update (nearest-centroid assignment, then per-cluster
     mean) of the preceding centroid matrix, within 1e-6 relative Frobenius
     error, or it is a Lloyd fixed point within 1e-3 (converged runs, e.g.
     library calls with a stopping tolerance). Empty clusters are skipped,
     since implementations legitimately differ in how they handle them.
  PASS if K1 and K2 hold. The inertia relative to the best of 10 k-means++
  restarts (scikit-learn) is reported for information only: a correct Lloyd
  run may legitimately stop in a worse local optimum.

Lysozyme -- a GROMACS energy minimisation must have run to completion:
  L1 a topology (.top) was generated by pdb2gmx;
  L2 an mdrun energy-minimisation report states convergence ("converged to
     Fmax" or "converged to machine precision");
  L3 the reported final potential energy is finite and negative.
  PASS if L1, L2 and L3 hold. Final Epot and whether the system was solvated
  are reported for information.

Output: oracle/oracle_results.csv (+ a per-row JSON detail file).
"""
