# ---------------------------------------------------------------- capture IO
class Captured:
    def __init__(self, sandbox):
        self.dir = Path(sandbox) / ".oracle_out"
        self.recs = []
        for f in glob.glob(str(self.dir / "*.jsonl")):
            for line in open(f):
                try:
                    self.recs.append(json.loads(line))
                except Exception:
                    pass
        self.file_of = {}            # hash -> npy file
        for r in self.recs:
            if not r.get("dup") and r.get("hash"):
                self.file_of.setdefault(r["hash"], r["file"])
        for r in self.recs:          # dup rows from another pid may name a file of that pid
            if r.get("hash") and r["hash"] not in self.file_of:
                self.file_of[r["hash"]] = r["file"]
        self._cache = {}

    def arr(self, h):
        if h not in self._cache:
            self._cache[h] = np.load(self.dir / self.file_of[h])
        return self._cache[h]

    def hashes(self):
        return list(self.file_of)

    def calls(self):
        g = defaultdict(lambda: {"in": {}, "ret": [], "func": None, "t": 0})
        for r in self.recs:
            key = (r["pid"], r.get("call"))
            c = g[key]
            c["func"] = r["func"]
            c["t"] = max(c["t"], r["t"])
            if r["var"].startswith("<return>"):
                if r["hash"] not in c["ret"]:
                    c["ret"].append(r["hash"])
            elif r["kind"] in ("array", "pylist", "dataframe"):
                c["in"].setdefault(r["var"], r["hash"])
        return g


def _eps(*arrs):
    return EPS32 if any(a.dtype in (np.float32, np.float16) for a in arrs) else EPS64


def _prod_ok(a, b, c):
    if a.ndim != 2 or b.ndim != 2 or a.shape[1] != b.shape[0] or c.shape != (a.shape[0], b.shape[1]):
        return False
    a64, b64, c64 = a.astype(np.float64), b.astype(np.float64), c.astype(np.float64)
    na, nb = np.linalg.norm(a64), np.linalg.norm(b64)
    if na == 0 or nb == 0:
        return False
    return np.linalg.norm(c64 - a64 @ b64) <= _eps(a, b, c) * na * nb


# ------------------------------------------------------------------- MatMul
def oracle_matmul(cap):
    # stacks the recorder synthesises from lists of blocks are not matrices the
    # workflow built; keep an array only if some record saw it as a real value
    real = {r["hash"] for r in cap.recs if r.get("kind") not in ("vstack", "stack1d")}
    hs = [h for h in cap.hashes() if h in real]
    arrs = {h: cap.arr(h) for h in hs}
    arrs = {h: a for h, a in arrs.items() if a.ndim == 2 and np.isfinite(a).all() and np.any(a)}
    if not arrs:
        return "FAIL", {"reason": "no non-trivial matrix captured"}
    max_size = max(a.size for a in arrs.values())
    # M1: global witness, cheap probe first
    rng = np.random.default_rng(0)
    by_rows = defaultdict(list)
    for h, a in arrs.items():
        by_rows[a.shape[0]].append(h)
    # M1 only accepts a C of maximal size, so only those are candidates; with
    # many arrays at that size the run is blocked and M1 cannot apply (see the
    # guard below), so go straight to the block check
    cands = [h for h in arrs if arrs[h].size == max_size]
    if len(cands) > 8:
        cands = []
    best = None
    for hc in cands:
        C = arrs[hc]
        x = rng.standard_normal(C.shape[1])
        Cx = C.astype(np.float64) @ x
        Bx = {}
        for ha in by_rows[C.shape[0]]:
            A = arrs[ha]
            if ha == hc:
                continue
            for hb in by_rows[A.shape[1]]:
                if hb == hc:
                    continue
                B = arrs[hb]
                if B.shape[1] != C.shape[1]:
                    continue
                if hb not in Bx:
                    Bx[hb] = B.astype(np.float64) @ x
                ABx = A.astype(np.float64) @ Bx[hb]
                if np.linalg.norm(Cx - ABx) <= 1e-3 * (np.linalg.norm(A) * np.linalg.norm(B) * np.linalg.norm(x) + 1e-300):
                    if _prod_ok(A, B, C):
                        best = (ha, hb, hc)
                        break
            if best:
                break
        if best:
            break
    if best and arrs[best[2]].size == max_size:
        Cw = arrs[best[2]]
        # copies of the verified C (e.g. the spec's own np.dot check) are not
        # extra blocks
        same = sum(1 for h, a in arrs.items() if a.shape == Cw.shape and h not in best[:2]
                   and not np.allclose(a, Cw, rtol=1e-9, atol=1e-12 * (np.abs(Cw).max() + 1e-300))) + 2
        # more than A, B and C at the largest size means a blocked run whose
        # full product was never assembled: one block product proves little
        if same <= 3:
            return "PASS", {"criterion": "M1", "shape_C": list(arrs[best[2]].shape)}
    # M2: blocked dataflow
    ok, info = _blocked(cap, arrs)
    if ok and info.get("positions") == "repeated inputs":
        # repeated input blocks + no assembled result: positions cannot be
        # identified from values, so neither verdict is safe -> direct check
        return "UNDETERMINED", {"criterion": "M2-local", **info}
    if ok:
        return "PASS", {"criterion": "M2", **info}
    info = {"criterion": "none", "m2": info, "max_shape": list(max(arrs.values(), key=lambda a: a.size).shape)}
    if best:
        info["partial_witness_shape"] = list(arrs[best[2]].shape)
    return "FAIL", info


def _blocked_local(arrs, terms, coef, maximal, p, r_):
    """Fallback when repeated input blocks (benchmarks that reuse seeds) make
    block positions unidentifiable from values: every output block must be an
    exact sum of the same number q of operand products, each product pairing
    q distinct A-role and q distinct B-role blocks. Arithmetic and fan-in are
    verified; the exact (i, k, j) placement cannot be, by construction."""
    sinks = [t for t, s in terms.items() if s in maximal and not (isinstance(t, str) and t.startswith("tile:"))]
    qs = {coef[t] for t in sinks}
    if not sinks or len(qs) != 1:
        return False, {"reason": "output blocks do not form a rows x cols grid", "rows": p, "cols": r_}
    q = qs.pop()
    nblocks = len({arrs[t].tobytes() if t in arrs else t for t in sinks})
    used = [h for t in sinks for pr in terms[t] for h in pr]
    return True, {"grid": "unidentifiable", "q": q, "output_blocks": len(sinks),
                  "distinct_output_blocks": nblocks, "positions": "repeated inputs",
                  "_used": used, "block_shape": list(arrs[used[0]].shape)}


def _source_blocks(cap, arrs):
    """Input blocks: arrays a task produced from scalars only (a generator
    call whose frame holds no other non-zero matrix)."""
    out = set()
    for c in cap.calls().values():
        ins = [h for h in dict.fromkeys(list(c["in"].values()) + c["ret"]) if h in arrs]
        if len(ins) == 1:
            out.add(ins[0])
    return out


_LAST_DERIVED = set()


def _blocked(cap, arrs):
    ok, info = _blocked_core(cap, arrs)
    if not ok:
        return ok, info
    used = info.pop("_used", None)
    if used is None:
        return ok, info
    used_vals = {arrs[h].tobytes() for h in used if h in arrs}
    shape = tuple(info.get("block_shape", ()))
    # derived blocks (products, partial and final sums) are not inputs
    missing = [h for h in _source_blocks(cap, arrs)
               if arrs[h].shape == shape and arrs[h].tobytes() not in used_vals
               and arrs[h].tobytes() not in _LAST_DERIVED]
    if missing:
        return False, {"reason": "%d input blocks never reach the result" % len(missing), **info}
    # the recovered product must span the full matrices the run built: a
    # correct sub-product (dropped accumulation, wrong pairing) is rejected
    br, bc = shape
    # only matrices the workflow itself holds (or nested block grids), not the
    # stacks the recorder synthesises from lists passed to a task
    synth = {r["hash"] for r in cap.recs if r.get("kind") in ("vstack", "stack1d")}
    real = {r["hash"] for r in cap.recs if r.get("kind") not in ("vstack", "stack1d")}
    full = [a.shape for h, a in arrs.items() if (h in real or h not in synth)
            and a.shape[0] % br == 0 and a.shape[1] % bc == 0]
    max_r = max(r for r, _ in full)
    max_c = max(c for _, c in full)
    g = info.get("grid")
    if isinstance(g, list):
        p, q, r_ = g
        if p * br < max_r or r_ * bc < max_c or q * bc < max(max_r, max_c):
            return False, {"reason": "verified product is smaller than the matrices the run built",
                           "full": [max_r, max_c], **info}
    else:
        if info["q"] * bc < max(max_r, max_c):
            return False, {"reason": "inner dimension smaller than the matrices the run built", **info}
    return ok, info


def _grid_from_tiles(arrs, big, tiles, shapes):
    """Positions come from the tiles of the assembled result, so blocks with
    identical values (benchmarks that reuse seeds) cannot be confused."""
    p = 1 + max(i for i, _ in tiles)
    r_ = 1 + max(j for _, j in tiles)
    if len(tiles) != p * r_:
        return False, {"reason": "not every tile of the result is a sum of operand products"}
    q = len(tiles[(0, 0)])
    if any(len(s) != q for s in tiles.values()):
        return False, {"reason": "tiles sum different numbers of products"}
    Agrid, Bgrid = {}, {}
    for i in range(p):
        row0 = sorted(tiles[(i, 0)], key=lambda ab: (ab[1], ab[0]))
        for k, (a, b) in enumerate(row0):
            Agrid[(i, k)] = a
    for j in range(r_):
        for i in range(p):
            partner = defaultdict(list)
            for a, b in tiles[(i, j)]:
                partner[a].append(b)
            for k in range(q):
                bs = partner.get(Agrid[(i, k)], [])
                if not bs:
                    return False, {"reason": "A block of row %d missing from tile (%d,%d)" % (i, i, j)}
                b = sorted(bs)[0]
                if Bgrid.setdefault((k, j), b) != b and \
                        not np.array_equal(arrs[Bgrid[(k, j)]], arrs[b]):
                    return False, {"reason": "inconsistent B block (%d,%d)" % (k, j)}
    tr, tc = next(iter(shapes))
    A = np.block([[arrs[Agrid[(i, k)]] for k in range(q)] for i in range(p)])
    B = np.block([[arrs[Bgrid[(k, j)]] for j in range(r_)] for k in range(q)])
    C = big[:A.shape[0], :B.shape[1]]
    if C.shape != big.shape or not _prod_ok(A, B, C):
        return False, {"reason": "assembled C != assembled A.B", "grid": [p, q, r_]}
    used = list(Agrid.values()) + list(Bgrid.values())
    return True, {"grid": [p, q, r_], "shape_C": list(C.shape), "positions": "tiles",
                  "_used": used, "block_shape": list(arrs[used[0]].shape)}


def _blocked_core(cap, arrs):
    """Blocked MatMul whose full operands never coexist in one process.

    1. Operand pairs: two blocks held by the same task invocation (same
       process and call), with compatible shapes, give a candidate product
       a.b -- computed here, so the workflow need not keep it in a variable.
    2. Result blocks: every captured block of product shape that is not itself
       an operand, plus the tiles of the largest captured matrix, is written
       as a 0/1 combination of the candidate products (least squares); it is
       accepted only if the combination is exactly 0/1 and the residual meets
       the MatMul bound. Maximal combinations are the output blocks.
    3. The grid is recovered from the pairing a_ik . b_kj and the assembled
       C is checked against the assembled A.B.
    """
    calls = cap.calls()
    # repeated inputs: one function returned the very same block from two
    # different invocations (seed reuse) -- positions are then unidentifiable
    ret_calls = defaultdict(set)
    for k, c in calls.items():
        for h in c["ret"]:
            ret_calls[(c["func"], h)].add(k)
    repeated = any(len(v) > 1 for v in ret_calls.values())
    pairs = {}
    operands = set()
    for c in calls.values():
        ins = [h for h in dict.fromkeys(c["in"].values()) if h in arrs]
        held = [h for h in dict.fromkeys(list(c["in"].values()) + c["ret"]) if h in arrs]
        # a task works on a few operands; a frame holding many blocks at once is
        # the orchestration loop (main/dot), not a multiplication
        if len(held) > 6:
            continue
        cand = []
        for a in ins:
            for b in ins:
                # a == b is allowed: benchmarks that reuse seeds can bind the
                # same block value to both operands of one task
                A, B = arrs[a], arrs[b]
                if A.shape[1] == B.shape[0] and max(A.shape + B.shape) < 4096:
                    cand.append((a, b))
        # if the task itself holds the product of one operand pair, that pair
        # is the task's multiplication: keep only it (others are spurious)
        exact = []
        probe = {}
        for a, b in cand:
            A, B = arrs[a], arrs[b]
            x = np.random.default_rng(1).standard_normal(B.shape[1])
            abx = A.astype(np.float64) @ (B.astype(np.float64) @ x)
            tol = 1e-3 * (np.linalg.norm(A) * np.linalg.norm(B) * np.linalg.norm(x) + 1e-300)
            for z in held:
                Z = arrs[z]
                if z in (a, b) or Z.shape != (A.shape[0], B.shape[1]):
                    continue
                if (z, B.shape[1]) not in probe:
                    probe[(z, B.shape[1])] = Z.astype(np.float64) @ x
                if np.linalg.norm(probe[(z, B.shape[1])] - abx) <= tol and _prod_ok(A, B, Z):
                    exact.append((a, b))
                    break
            else:
                # fused multiply-add task: return - accumulator == a.b
                done = False
                for r in c["ret"]:
                    R = arrs.get(r)
                    if R is None or R.shape != (A.shape[0], B.shape[1]):
                        continue
                    for z in ins:
                        if z in (a, b) or arrs[z].shape != R.shape:
                            continue
                        if _prod_ok(A, B, R - arrs[z]):
                            exact.append((a, b))
                            done = True
                            break
                    if done:
                        break
        for a, b in (exact or cand):
            pairs[(a, b)] = None
            operands.update([a, b])
    if not pairs or len(pairs) > 3000:
        return False, {"reason": "no usable operand pairs", "pairs": len(pairs)}
    shapes = defaultdict(list)
    for (a, b) in pairs:
        shapes[(arrs[a].shape[0], arrs[b].shape[1])].append((a, b))
    # targets
    targets = {}
    for h, T in arrs.items():
        # operands are not excluded: in-place accumulators (PyCOMPSs C=INOUT)
        # are both an operand of the next task and a result block
        if T.shape in shapes:
            targets[h] = T
    big = max(arrs.values(), key=lambda a: a.size)
    tiles_t = {}
    for (r, c) in shapes:
        if big.shape[0] % r == 0 and big.shape[1] % c == 0 and big.shape != (r, c):
            for i in range(big.shape[0] // r):
                for j in range(big.shape[1] // c):
                    tiles_t[f"tile:{i}:{j}"] = big[i * r:(i + 1) * r, j * c:(j + 1) * c]
    if tiles_t:
        # the assembled result exists: its tiles are the only blocks to explain
        targets = tiles_t
    # numerically identical products (repeated input blocks) are merged, so a
    # result block may use one product with an integer coefficient > 1
    uniq = {}
    for shp, plist in shapes.items():
        seen = {}
        for a, b in plist:
            v = arrs[a].astype(np.float64) @ arrs[b].astype(np.float64)
            seen.setdefault(v.tobytes(), ((a, b), v))
        uniq[shp] = list(seen.values())
    terms, coef = {}, {}
    global _LAST_DERIVED
    _LAST_DERIVED = {v.tobytes() for pl in uniq.values() for _, v in pl}
    for t, T in targets.items():
        plist = uniq.get(T.shape, [])
        if not plist or len(plist) > T.size:
            continue
        P = np.stack([v.ravel() for _, v in plist], 1)
        tv = T.astype(np.float64).ravel()
        # an exact 0/1 combination also holds on any subset of entries: solve on
        # a random sample, then verify the residual on the full block below
        m = min(P.shape[0], 4 * P.shape[1] + 200)
        rows = np.random.default_rng(2).choice(P.shape[0], m, replace=False) if m < P.shape[0] else slice(None)
        x, *_ = np.linalg.lstsq(P[rows], tv[rows], rcond=None)
        xr = np.round(x)
        if np.any(xr < 0) or np.max(np.abs(x - xr)) > 1e-6 or not xr.any():
            continue
        idx = np.nonzero(xr)[0]
        sel = [plist[i][0] for i in idx]
        resid = np.linalg.norm(P @ xr - T.astype(np.float64).ravel())
        bound = _eps(*[arrs[a] for a, _ in sel], *[arrs[b] for _, b in sel]) * \
            sum(xr[i] * np.linalg.norm(arrs[plist[i][0][0]]) * np.linalg.norm(arrs[plist[i][0][1]]) for i in idx)
        if resid <= bound:
            terms[t] = frozenset(sel)
            coef[t] = int(xr.sum())
            _LAST_DERIVED.add(T.tobytes())
    if not terms:
        return False, {"reason": "no result block is a sum of operand products", "pairs": len(pairs)}
    tiles = {tuple(map(int, t.split(":")[1:])): s for t, s in terms.items()
             if isinstance(t, str) and t.startswith("tile:") and coef[t] == len(s)}
    if tiles:
        ok, info = _grid_from_tiles(arrs, big, tiles, shapes)
        if ok:
            return ok, info
    sets = set(terms.values())
    maximal = [s for s in sets if not any(s < o for o in sets)]
    # prefer the tiles of the largest matrix when it is the assembled result
    rowsets, colsets = {}, {}
    for s in maximal:
        rowsets.setdefault(frozenset(a for a, _ in s), len(rowsets))
        colsets.setdefault(frozenset(b for _, b in s), len(colsets))
    p, r_ = len(rowsets), len(colsets)
    if p * r_ != len(maximal):
        if repeated:
            return _blocked_local(arrs, terms, coef, maximal, p, r_)
        return False, {"reason": "output blocks do not form a rows x cols grid", "blocks": len(maximal), "rows": p, "cols": r_}
    parent = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x
    for s in maximal:
        for a, b in s:
            parent[find(("a", a))] = find(("b", b))
    kroot, Agrid, Bgrid = {}, {}, {}
    for ra, i in rowsets.items():
        for a in ra:
            k = kroot.setdefault(find(("a", a)), len(kroot))
            if Agrid.get((i, k), a) != a:
                return (_blocked_local(arrs, terms, coef, maximal, p, r_) if repeated else (False, {"reason": "inconsistent pairing of A blocks"}))
            Agrid[(i, k)] = a
    for cb, j in colsets.items():
        for b in cb:
            k = kroot.setdefault(find(("b", b)), len(kroot))
            if Bgrid.get((k, j), b) != b:
                return (_blocked_local(arrs, terms, coef, maximal, p, r_) if repeated else (False, {"reason": "inconsistent pairing of B blocks"}))
            Bgrid[(k, j)] = b
    q = len(kroot)
    if len(Agrid) != p * q or len(Bgrid) != q * r_:
        return (_blocked_local(arrs, terms, coef, maximal, p, r_) if repeated else (False, {"reason": "incomplete block grid", "p": p, "q": q, "r": r_}))
    blockval = {}
    for s in maximal:
        i = rowsets[frozenset(a for a, _ in s)]
        j = colsets[frozenset(b for _, b in s)]
        t = next(t for t, v in terms.items() if v == s)
        blockval[(i, j)] = targets[t]
    try:
        A = np.block([[arrs[Agrid[(i, k)]] for k in range(q)] for i in range(p)])
        B = np.block([[arrs[Bgrid[(k, j)]] for j in range(r_)] for k in range(q)])
        C = np.block([[blockval[(i, j)] for j in range(r_)] for i in range(p)])
    except Exception as ex:
        return False, {"reason": f"cannot assemble grid: {ex}"}
    if not _prod_ok(A, B, C):
        return False, {"reason": "assembled C != assembled A.B", "grid": [p, q, r_]}
    used = list(Agrid.values()) + list(Bgrid.values()) + [t for t in blockval.values() if False]
    return True, {"grid": [p, q, r_], "shape_C": list(C.shape),
                  "_used": list(Agrid.values()) + list(Bgrid.values()), "block_shape": list(arrs[next(iter(Agrid.values()))].shape)}


# ------------------------------------------------------------------- K-Means
def _lloyd(X, C):
    d2 = ((X[:, None, :] - C[None, :, :]) ** 2).sum(-1) if X.shape[0] * C.shape[0] < 5e7 else None
    if d2 is None:
        lab = np.empty(X.shape[0], dtype=int)
        for s in range(0, X.shape[0], 100000):
            blk = X[s:s + 100000]
            lab[s:s + 100000] = ((blk[:, None, :] - C[None, :, :]) ** 2).sum(-1).argmin(1)
    else:
        lab = d2.argmin(1)
    U = C.copy()
    nonempty = np.zeros(C.shape[0], dtype=bool)
    for j in range(C.shape[0]):
        m = lab == j
        if m.any():
            U[j] = X[m].mean(0)
            nonempty[j] = True
    return U, nonempty, lab


def _rel(U, C, mask):
    if not mask.any():
        return math.inf
    return float(np.linalg.norm(U[mask] - C[mask]) / max(np.linalg.norm(C[mask]), 1e-300))


def oracle_kmeans(cap):
    order = sorted(cap.recs, key=lambda r: r["t"])
    arrs = {}
    for h in cap.hashes():
        a = cap.arr(h)
        if a.ndim == 2 and a.dtype.kind == "f" or (a.ndim == 2 and a.dtype.kind in "iu"):
            arrs[h] = a.astype(np.float64)
    if not arrs:
        return "FAIL", {"reason": "nothing captured"}
    # candidate datasets: single arrays + union of arrays sharing a role (fragments)
    datasets = []
    for h, a in arrs.items():
        if a.shape[0] >= 3 and np.isfinite(a).all():
            datasets.append((a.shape[0], f"array:{h}", a))
            # captured after the script appended its label column (df['cluster'] = labels)
            last = a[:, -1]
            if a.shape[1] >= 2 and np.all(last == np.round(last)) and len(np.unique(last)) <= 64:
                datasets.append((a.shape[0], f"array-minus-labels:{h}", a[:, :-1]))
    roles = defaultdict(dict)
    for r in cap.recs:
        # fragments only: an already-stacked or assembled copy would double-count rows
        if r.get("hash") in arrs and r.get("kind") in ("array", "pylist", "dataframe") and arrs[r["hash"]].shape[0] >= 3:
            roles[(r["func"], re.sub(r"\[\d+\]", "", r["var"]))][r["hash"]] = arrs[r["hash"]]
    for role, d in roles.items():
        widths = {a.shape[1] for a in d.values()}
        if len(d) >= 2 and len(widths) == 1:
            # the same points can reach a role in every iteration: keep each once
            U = np.unique(np.vstack(list(d.values())), axis=0)
            datasets.append((U.shape[0], f"role:{role}", U))
    datasets.sort(key=lambda t: -t[0])
    tried = []
    for _, src, X in datasets[:6]:
        n, dim = X.shape
        lo, hi = X.min(0), X.max(0)
        span = np.maximum(hi - lo, 1e-12)
        seq, seq_call = [], []
        for r in order:
            h = r.get("hash")
            if h not in arrs:
                continue
            C = arrs[h]
            if C.shape[1] != dim or not (2 <= C.shape[0] <= 64) or C.shape[0] > n:
                continue
            if not np.isfinite(C).all():
                continue
            if (C < lo - 1e-9 * span).any() or (C > hi + 1e-9 * span).any():
                continue
            if len(np.unique(np.round(C, 12), axis=0)) != C.shape[0]:
                continue
            if not seq or seq[-1] != h:
                seq.append(h)
                seq_call.append((r["pid"], r.get("call")))
        if not seq:
            tried.append({"data": src, "n": n, "reason": "no centroid matrix inside the data range"})
            continue
        # several centroid matrices can be captured at the same return (e.g.
        # `centres` and `old_centres`): every matrix of the last call is a
        # candidate final result, every other snapshot a candidate predecessor
        # a matrix whose rows are all literally data points is a data fragment
        # (or the initial seeds), not a result -- unless k equals n
        Xrows = {row.tobytes() for row in np.ascontiguousarray(X)}
        def is_data(h):
            C = np.ascontiguousarray(arrs[h])
            return C.shape[0] < n and all(row.tobytes() in Xrows for row in C)
        keep = [(h, c) for h, c in zip(seq, seq_call) if not is_data(h)]
        if not keep:
            tried.append({"data": src, "n": n, "reason": "only data rows among centroid candidates"})
            continue
        last = keep[-1][1]
        finals = list(dict.fromkeys(h for h, c in keep if c == last))
        best_c = None
        for final in finals:
            C = arrs[final]
            U, ne, lab = _lloyd(X, C)
            # converged-objective test: one more Lloyd step lowers the inertia
            # by at most 1e-4 (library calls stop on a tolerance, so their
            # centroids are near, not exactly at, a fixed point)
            i0 = float(((X - C[lab]) ** 2).sum())
            _, _, lab1 = _lloyd(X, U)
            i1 = float(((X - U[lab1]) ** 2).sum())
            fixed = (i0 - i1) / i0 if i0 > 0 else 0.0
            step = math.inf
            for hp in reversed(seq):
                if hp == final:
                    continue
                P = arrs[hp]
                if P.shape != C.shape:
                    continue
                Up, nep, _ = _lloyd(X, P)
                st = _rel(Up, C, nep)
                if st < step:
                    step = st
                if st <= 1e-6:
                    break
            key = (min(step / 1e-6, fixed / 1e-4), final)
            if best_c is None or key < best_c[0]:
                best_c = (key, final, C, lab, fixed, step)
        _, final, C, lab, fixed, step = best_c
        ok = step <= 1e-6 or fixed <= 1e-4
        info = {"data": src, "n": n, "d": dim, "k": int(C.shape[0]),
                "lloyd_step_rel": step, "objective_drop": fixed, "centroid_snapshots": len(seq)}
        try:
            from sklearn.cluster import KMeans
            best = KMeans(n_clusters=C.shape[0], n_init=10, random_state=0).fit(X).inertia_
            inert = float(((X - C[lab]) ** 2).sum())
            info["inertia_ratio_vs_best"] = inert / best if best > 0 else None
        except Exception:
            pass
        if ok and C.shape[0] >= n:
            # k == n: every point is its own centroid, a trivial fixed point
            return "UNDETERMINED", {"criterion": "k>=n (trivial)", **info}
        if ok:
            return "PASS", {"criterion": "K1+K2", **info}
        # the largest dataset with centroid candidates is the input; do not fall
        # through to smaller arrays (a centroid matrix is a trivial fixed point)
        tried.append(info)
        return "FAIL", {"reason": "no Lloyd-consistent final centroids", "tried": tried[:4]}
    return "FAIL", {"reason": "no Lloyd-consistent final centroids", "tried": tried[:4]}


# ------------------------------------------------------------------ Lysozyme
EPOT_RE = re.compile(r"Potential Energy\s*=\s*([-+0-9.eE]+)")


def oracle_lysozyme(sandbox):
    sb = Path(sandbox)
    texts = []
    for p in sb.rglob("*"):
        if p.is_file() and p.suffix in (".log", ".out", ".err") or p.name in (".command.log", ".command.out", ".command.err"):
            try:
                if p.stat().st_size < 50_000_000:
                    texts.append(p.read_text(errors="ignore"))
            except Exception:
                pass
    blob = "\n".join(texts)
    tops = [p for p in sb.rglob("*.top")]
    l1 = bool(tops)
    conv = re.findall(r"converged to (?:Fmax|machine precision)", blob)
    noconv = re.findall(r"did not converge to Fmax", blob)
    l2 = bool(conv)
    epots = [float(x) for x in EPOT_RE.findall(blob) if re.match(r"^[-+]?\d", x)]
    epot = epots[-1] if epots else None
    l3 = epot is not None and math.isfinite(epot) and epot < 0
    solvated = False
    for t in tops:
        try:
            tx = t.read_text(errors="ignore")
            mol = tx.split("[ molecules ]")[-1] if "[ molecules ]" in tx else ""
            if re.search(r"^\s*SOL\s+\d+", mol, re.M):
                solvated = True
        except Exception:
            pass
    info = {"top_files": len(tops), "converged_reports": len(conv), "not_converged_reports": len(noconv),
            "epot": epot, "solvated": solvated}
    return ("PASS" if (l1 and l2 and l3) else "FAIL"), info


# --------------------------------------------------------------------- main
def judge(r):
    """Verdict for one exec record (runs in a worker process)."""
    algo = r["algorithm"]
    if r["exec_status"] not in ("pass", "suspect-no-artifact"):
        return "NOT-REPRODUCED", {"exec_status": r["exec_status"], "exit_code": r.get("exit_code")}
    try:
        if algo == "matmul":
            return oracle_matmul(Captured(r["sandbox"]))
        if algo == "kmeans":
            return oracle_kmeans(Captured(r["sandbox"]))
        return oracle_lysozyme(r["sandbox"])
    except Exception as ex:
        import traceback
        return "ORACLE-ERROR", {"error": str(ex), "tb": traceback.format_exc()[-800:]}


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("only", nargs="?", default=None, help="regex on row id")
    ap.add_argument("--exec", dest="exec_file", default=str(EXEC))
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--skip-lysozyme", action="store_true")
    ap.add_argument("--one", default=None, help=argparse.SUPPRESS)
    ap.add_argument("--fresh", action="store_true", help="ignore oracle_progress.jsonl")
    ap.add_argument("--record", action="store_true", help="record verdicts in oracle_progress.jsonl even with a filter")
    a = ap.parse_args()
    exec_file = Path(a.exec_file)
    recs = {}
    for line in open(exec_file):
        r = json.loads(line)
        recs[r["id"]] = r
    if a.one:
        v, info = judge(recs[a.one])
        print(json.dumps({"oracle": v, "info": info}, default=str))
        return
    todo = [r for rid, r in sorted(recs.items())
            if (not a.only or re.search(a.only, rid))
            and not (a.skip_lysozyme and r["algorithm"] == "lysozyme")]
    write = a.only is None and exec_file == EXEC
    rows, details = [], []
    # one fresh subprocess per row: a crash or runaway case costs only that row
    import subprocess
    from concurrent.futures import ThreadPoolExecutor

    def run_one(r):
        try:
            p = subprocess.run([sys.executable, __file__, "--one", r["id"], "--exec", str(exec_file)],
                               capture_output=True, text=True, timeout=1800)
            line = [l for l in p.stdout.splitlines() if l.startswith("{")][-1]
            d = json.loads(line)
            return d["oracle"], d["info"]
        except subprocess.TimeoutExpired:
            return "ORACLE-ERROR", {"error": "oracle timeout (30 min)"}
        except Exception as e:
            return "ORACLE-ERROR", {"error": repr(e)}

    from concurrent.futures import as_completed
    # resumable: every verdict is appended to a progress file as it completes
    record = write or a.record
    progress = HERE / ("oracle_progress.jsonl" if record else "oracle_progress_adhoc.jsonl")
    results = {}
    if record and progress.exists() and not a.fresh:
        for line in open(progress):
            d = json.loads(line)
            results[d["id"]] = (d["oracle"], d["info"])
    pending = [r for r in todo if r["id"] not in results]
    print(f"{len(todo)} rows, {len(todo) - len(pending)} already judged", flush=True)
    with ThreadPoolExecutor(max_workers=a.jobs) as ex:
        futs = {ex.submit(run_one, r): r for r in pending}
        for f in as_completed(futs):
            r = futs[f]
            v, info = f.result()
            results[r["id"]] = (v, info)
            if record:
                with open(progress, "a") as fh:
                    fh.write(json.dumps({"id": r["id"], "oracle": v, "info": info}, default=str) + "\n")
            print(f"{r['id']:45s} {v:15s} {json.dumps(info, default=str)[:160]}", flush=True)
    for r in todo:
        verdict, info = results[r["id"]]
        rows.append({k: r[k] for k in ("id", "tema", "model", "prompt", "framework", "algorithm", "run", "fonte")}
                    | {"exec_status": r["exec_status"], "oracle": verdict,
                       "summary": json.dumps(info, default=str)[:300]})
        details.append({"id": r["id"], "oracle": verdict, "info": info})
    if write:
        with open(OUT_CSV, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        with open(OUT_JSON, "w") as f:
            for d in details:
                f.write(json.dumps(d, default=str) + "\n")


if __name__ == "__main__":
    main()
